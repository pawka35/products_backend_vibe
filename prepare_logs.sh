#!/bin/bash
# Скрипт для подготовки директории logs на хосте перед запуском контейнеров

set -e

LOGS_DIR="./logs"

echo "🔍 Подготовка директории логов на хосте: $LOGS_DIR"

# Проверяем, существует ли директория
if [ ! -d "$LOGS_DIR" ]; then
    echo "📁 Директория $LOGS_DIR не существует, создаём..."
    mkdir -p "$LOGS_DIR"
    echo "✅ Директория создана"
else
    echo "✅ Директория существует"
fi

# Устанавливаем права на запись для всех
echo "🔐 Установка прав на директорию..."
chmod 777 "$LOGS_DIR" || echo "⚠️  Не удалось установить права 777, пробуем 755..."
chmod 755 "$LOGS_DIR" || echo "⚠️  Не удалось установить права 755"

# Проверяем права
echo "📊 Информация о директории:"
ls -ld "$LOGS_DIR"

# Проверяем, можем ли создать тестовый файл
TEST_FILE="$LOGS_DIR/.test_write"
if touch "$TEST_FILE" 2>/dev/null; then
    echo "✅ Можем создавать файлы в директории"
    rm -f "$TEST_FILE"
else
    echo "⚠️  Не можем создавать файлы в директории"
    echo "⚠️  Проверьте права доступа к директории"
fi

echo "✅ Подготовка директории логов завершена"

