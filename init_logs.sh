#!/bin/bash
# Скрипт для инициализации директории logs перед запуском приложения

set -e

LOGS_DIR="/app/logs"

echo "🔍 Проверка директории логов: $LOGS_DIR"

# Проверяем, существует ли директория
if [ ! -d "$LOGS_DIR" ]; then
    echo "📁 Директория $LOGS_DIR не существует, создаём..."
    mkdir -p "$LOGS_DIR"
    echo "✅ Директория создана"
else
    echo "✅ Директория существует"
fi

# Проверяем права на запись
if [ -w "$LOGS_DIR" ]; then
    echo "✅ Есть права на запись в директорию"
else
    echo "⚠️  Нет прав на запись, пытаемся изменить права..."
    chmod 777 "$LOGS_DIR" 2>/dev/null || echo "⚠️  Не удалось изменить права (это нормально, если volume монтируется из хоста)"
fi

# Проверяем владельца
echo "📊 Информация о директории:"
ls -ld "$LOGS_DIR" || echo "⚠️  Не удалось получить информацию"

# Проверяем, можем ли создать тестовый файл
TEST_FILE="$LOGS_DIR/.test_write"
if touch "$TEST_FILE" 2>/dev/null; then
    echo "✅ Можем создавать файлы в директории"
    rm -f "$TEST_FILE"
else
    echo "⚠️  Не можем создавать файлы в директории"
    echo "⚠️  Логи будут выводиться только в консоль"
fi

echo "✅ Инициализация директории логов завершена"

